log = logging.getLogger(__name__)

JOBS_DIR = ".lcc/jobs"


class Scheduler(Protocol):
    async def start(self) -> None: ...
    async def stop(self) -> None: ...
    async def cancel(self, job_id: int) -> None: ...
    def wake(self) -> None: ...
    def wait_reason(self, job_id: int) -> str | None: ...


# ---------------------------------------------------------------- placement (pure)


def free_gpus(snapshot: MetricsSnapshot | None, reserved: set[int], max_mem_frac: float, max_util: float) -> list[int]:
    if snapshot is None:
        return []
    out = []
    for g in snapshot.gpus:
        if g.index in reserved:
            continue
        mem_frac = g.memory_used / g.memory_total if g.memory_total else 1.0
        if mem_frac <= max_mem_frac and g.utilization <= max_util:
            out.append(g.index)
    return out


@dataclass
class Placement:
    job_id: int
    gpu_indices: list[int]


def place(
    queued: Sequence[Job], running_count: int, max_jobs: int, free: list[int], gpu_count: int
) -> tuple[list[Placement], dict[int, str]]:
    """FIFO with backfill: earlier jobs get first pick; a job that does not fit does not block
    smaller ones behind it. Returns placements and a wait reason for every job left queued."""
    placements: list[Placement] = []
    reasons: dict[int, str] = {}
    available = list(free)
    slots = max_jobs - running_count
    for job in queued:
        if slots <= 0:
            reasons[job.id] = f"Server at max concurrent jobs ({max_jobs})"
            continue
        need = job.gpus_requested
        if need > gpu_count:
            reasons[job.id] = f"Requests {need} GPUs but server has {gpu_count}"
            continue
        if need > len(available):
            reasons[job.id] = f"Waiting for {need} free GPU{'s' if need > 1 else ''} ({len(available)} free)"
            continue
        chosen, available = available[:need], available[need:]
        placements.append(Placement(job.id, chosen))
        slots -= 1
    return placements, reasons


# ---------------------------------------------------------------- remote scripts


def _cd_line(working_dir: str) -> str:
    if working_dir == "~":
        return 'cd "$HOME"'
    if working_dir.startswith("~/"):
        return f'cd "$HOME"/{shlex.quote(working_dir[2:])}'
    return f"cd {shlex.quote(working_dir)}"


def render_run_script(job: Job, job_dir: str, gpu_indices: list[int]) -> str:
    lines = [
        "#!/usr/bin/env bash",
        f"# Generated by Lab Server Control Center for job {job.id} ({job.name})",
        f"export CUDA_VISIBLE_DEVICES={shlex.quote(','.join(map(str, gpu_indices)))}" if gpu_indices else
        "export CUDA_VISIBLE_DEVICES=''" if job.gpus_requested == 0 else "",
        f"export LCC_JOB_ID={job.id}",
        f"export LCC_JOB_NAME={shlex.quote(job.name)}",
        f"export LCC_PROGRESS_FILE={shlex.quote(job_dir + '/progress')}",
    ]
    lines += [f"export {k}={shlex.quote(v)}" for k, v in job.env.items()]
    lines += [
        _cd_line(job.working_dir)
        + f" || {{ echo {shlex.quote('working directory not found: ' + job.working_dir)} >&2; exit 127; }}",
        job.command,
        "",
    ]
    return "\n".join(line for line in lines if line != "")


def _launch_command(job_dir: str) -> str:
    # `setsid -f` forks into a new session and returns immediately (a plain `setsid ... &` keeps
    # the SSH channel open for the job's lifetime). The session leader records its own pid,
    # which is also the process-group id used for cancellation.
    inner = (
        "echo $$ > pid; bash -l ./run.sh > stdout.log 2> stderr.log; "
        "echo $? > exit_code.tmp; mv exit_code.tmp exit_code"
    )
    return (
        f"cd {shlex.quote(job_dir)} && rm -f pid exit_code exit_code.tmp progress && "
        f"setsid -f bash -c {shlex.quote(inner)} > /dev/null 2>&1 < /dev/null && "
        "for i in $(seq 1 50); do [ -s pid ] && break; sleep 0.1; done; cat pid"
    )


def _poll_command(jobs: Sequence[Job], home: str) -> str:
    parts = []
    for job in jobs:
        d = shlex.quote(f"{home}/{JOBS_DIR}/{job.id}")
        pid = int(job.pid or 0)
        parts.append(
            f'ec=$(cat {d}/exit_code 2>/dev/null); '
            f'if kill -0 {pid} 2>/dev/null; then alive=1; else alive=0; fi; '
            f'pr=$(head -c 32 {d}/progress 2>/dev/null | tr -d "\\n|"); '
            f'echo "{job.id}|$ec|$alive|$pr"'
        )
    return "; ".join(parts) or "true"


def _parse_progress(raw: str) -> float | None:
    raw = raw.strip()
    try:
        value = float(raw[:-1]) / 100 if raw.endswith("%") else float(raw)
    except ValueError:
        return None
    return max(0.0, min(1.0, value / 100 if value > 1 else value))


# ---------------------------------------------------------------- scheduler


class LocalGpuScheduler:
    def __init__(self, sftp: SFTPManager, hub: MetricsHub) -> None:
        self._sftp = sftp
        self._hub = hub
        self._task: asyncio.Task[None] | None = None
        self._wake = asyncio.Event()
        self._lock = asyncio.Lock()
        self._reasons: dict[int, str] = {}
        self._kill_tasks: set[asyncio.Task[None]] = set()

    async def start(self) -> None:
        self._task = asyncio.create_task(self._loop(), name="job-scheduler")

    async def stop(self) -> None:
        if self._task:
            self._task.cancel()
            with contextlib.suppress(asyncio.CancelledError):
                await self._task
        for t in list(self._kill_tasks):
            t.cancel()

    def wake(self) -> None:
        self._wake.set()

    def wait_reason(self, job_id: int) -> str | None:
        return self._reasons.get(job_id)

    async def _loop(self) -> None:
        interval = get_settings().scheduler_interval_s
        while True:
            try:
                await self.tick()
            except asyncio.CancelledError:
                raise
            except Exception:  # noqa: BLE001
                log.exception("scheduler tick failed")
            with contextlib.suppress(asyncio.TimeoutError):
                await asyncio.wait_for(self._wake.wait(), timeout=interval)
            self._wake.clear()

    async def tick(self) -> None:
        async with self._lock:
            async with SessionLocal() as db:
                servers = {s.id: s for s in await db.scalars(select(Server))}
                active = list(
                    await db.scalars(
                        select(Job).where(Job.status.in_(("queued", "running"))).order_by(Job.created_at, Job.id)
                    )
                )
            by_server: dict[int, list[Job]] = {}
            for job in active:
                by_server.setdefault(job.server_id, []).append(job)
            reasons: dict[int, str] = {}
            await asyncio.gather(
                *(self._tick_server(servers.get(sid), jobs, reasons) for sid, jobs in by_server.items())
            )
            self._reasons = reasons

    async def _tick_server(self, server: Server | None, jobs: list[Job], reasons: dict[int, str]) -> None:
        if server is None:
            return
        queued = [j for j in jobs if j.status == "queued"]
        if server.transport != "ssh":
            for j in queued:
                reasons[j.id] = "Simulated servers cannot run jobs"
            return
        try:
            running = await self._poll(server, [j for j in jobs if j.status == "running"])
        except (SSHError, RemoteFileError, asyncssh.Error, OSError) as exc:
            for j in queued:
                reasons[j.id] = f"Server unreachable: {exc}"
            return
        if not queued:
            return

        runtime = self._hub.get(server.id)
        online = bool(runtime and runtime.status.state == "online" and runtime.latest)
        if not online:
            for j in queued:
                reasons[j.id] = "Waiting for live metrics from server"
            return
        snapshot = runtime.latest  # type: ignore[union-attr]
        reserved = {i for j in running for i in (j.gpu_indices or [])}
        settings = get_settings()
        free = free_gpus(snapshot, reserved, settings.gpu_free_max_mem_frac, settings.gpu_free_max_util)
        placements, waiting = place(queued, len(running), server.max_jobs, free, len(snapshot.gpus))  # type: ignore[union-attr]
        reasons.update(waiting)
        by_id = {j.id: j for j in queued}
        for p in placements:
            try:
                await self._launch(server, by_id[p.job_id], p.gpu_indices)
            except Exception as exc:  # noqa: BLE001
                log.warning("failed to launch job %s: %s", p.job_id, exc)
                await self._set(p.job_id, status="failed", error=f"Launch failed: {str(exc) or exc.__class__.__name__}", ended_at=utcnow())

    # ------------------------------------------------------------------ remote ops

    async def _job_dir(self, server: Server, job_id: int) -> str:
        return posixpath.join(await self._sftp.home(server), JOBS_DIR, str(job_id))

    async def _launch(self, server: Server, job: Job, gpu_indices: list[int]) -> None:
        job_dir = await self._job_dir(server, job.id)
        await self._sftp.makedirs(server, job_dir)
        script = render_run_script(job, job_dir, gpu_indices)
        sftp = await self._sftp.client(server)
        async with sftp.open(posixpath.join(job_dir, "run.sh"), "w") as f:
            await f.write(script)
        conn = await self._sftp.connection(server)
        result = await asyncio.wait_for(conn.run(_launch_command(job_dir), check=False), timeout=20)
        pid_text = str(result.stdout or "").strip().splitlines()[-1:] or [""]
        if result.exit_status not in (0, None) or not pid_text[0].isdigit():
            raise RuntimeError(str(result.stderr or "").strip() or "could not start process")
        await self._set(
            job.id, status="running", pid=int(pid_text[0]), gpu_indices=gpu_indices, started_at=utcnow(),
            ended_at=None, exit_code=None, error=None, progress=None,
            stdout_path=f"{job_dir}/stdout.log", stderr_path=f"{job_dir}/stderr.log",
        )
        log.info("started job %s on %s (pid %s, gpus %s)", job.id, server.name, pid_text[0], gpu_indices)

    async def _poll(self, server: Server, running: list[Job]) -> list[Job]:
        """Update running jobs; return those still running."""
        if not running:
            return []
        home = await self._sftp.home(server)
        conn = await self._sftp.connection(server)
        result = await asyncio.wait_for(conn.run(_poll_command(running, home), check=False), timeout=20)
        seen: dict[int, tuple[str, str, str]] = {}
        for line in str(result.stdout or "").splitlines():
            parts = line.split("|")
            if len(parts) == 4 and parts[0].isdigit():
                seen[int(parts[0])] = (parts[1].strip(), parts[2].strip(), parts[3])
        still: list[Job] = []
        for job in running:
            if job.id not in seen:
                still.append(job)
                continue
            exit_code, alive, progress = seen[job.id]
            if exit_code.lstrip("-").isdigit():
                code = int(exit_code)
                await self._set(
                    job.id, status="completed" if code == 0 else "failed", exit_code=code, ended_at=utcnow(),
                    progress=1.0 if code == 0 else job.progress,
                    error=None if code == 0 else f"Exited with code {code}",
                )
            elif alive == "0":
                await self._set(
                    job.id, status="failed", ended_at=utcnow(),
                    error="Process disappeared without an exit code (killed, OOM or server reboot?)",
                )
            else:
                still.append(job)
                value = _parse_progress(progress) if progress else None
                if value is not None and value != job.progress:
                    await self._set(job.id, progress=value)
        return still

    async def cancel(self, job_id: int) -> None:
        async with self._lock:
            async with SessionLocal() as db:
                job = await db.get(Job, job_id)
                if job is None or job.status not in ("queued", "running"):
                    return
                server = await db.get(Server, job.server_id)
                pid = job.pid if job.status == "running" else None
                job.status, job.ended_at, job.error = "canceled", utcnow(), "Canceled by user"
                await db.commit()
        if pid and server is not None:
            conn = await self._sftp.connection(server)
            await conn.run(f"kill -TERM -- -{int(pid)} 2>/dev/null || kill -TERM {int(pid)}", check=False)
            task = asyncio.create_task(self._kill_later(server, int(pid)))
            self._kill_tasks.add(task)
            task.add_done_callback(self._kill_tasks.discard)
        self.wake()

    async def _kill_later(self, server: Server, pid: int, delay: float = 10.0) -> None:
        await asyncio.sleep(delay)
        with contextlib.suppress(Exception):
            conn = await self._sftp.connection(server)
            await conn.run(f"kill -0 {pid} 2>/dev/null && kill -KILL -- -{pid} 2>/dev/null", check=False)

    @staticmethod
    async def _set(job_id: int, **fields: object) -> None:
        async with SessionLocal() as db:
            job = await db.get(Job, job_id)
            if job is None:
                return
            # Never resurrect a job the user canceled while we were working on it.
            if job.status == "canceled" and fields.get("status") not in (None, "canceled"):
                return
            for key, value in fields.items():
                setattr(job, key, value)
            await db.commit()
