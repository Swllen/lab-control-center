"""Job scheduling.

``Scheduler`` is the seam for swapping implementations (e.g. a ``SlurmScheduler`` mapping to
sbatch/squeue/scancel). ``LocalGpuScheduler`` is a lightweight per-server queue:

* every tick it polls running jobs (pid alive? exit code? progress file?) with one SSH exec per
  server, then places queued jobs FIFO (with backfill) onto GPUs that are idle according to live
  metrics and not assigned to another control-center job, respecting ``Server.max_jobs``;
* a job runs detached on the server (``setsid nohup``) from ``~/.lcc/jobs/<id>/run.sh`` so it
  survives SSH drops and control-center restarts; stdout/stderr/exit code live next to it.
"""

from __future__ import annotations

import asyncio
import contextlib
import logging
import posixpath
import shlex
from collections.abc import Sequence
